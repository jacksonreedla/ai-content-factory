def _deep_merge(base: dict, override: dict) -> dict:
    """Return ``base`` recursively overridden by ``override``."""
    out = copy.deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(out.get(key), dict):
            out[key] = _deep_merge(out[key], value)
        else:
            out[key] = value
    return out


class Config:
    """Thread-safe config with dot-path get/set, persisted as JSON."""

    def __init__(self, data: dict[str, Any]):
        self._data = data
        self._lock = threading.RLock()

    # ---------------------------------------------------------------- load/save
    @classmethod
    def load(cls) -> "Config":
        data: dict[str, Any] = {}
        if CONFIG_PATH.exists():
            try:
                data = json.loads(CONFIG_PATH.read_text(encoding="utf-8"))
            except (json.JSONDecodeError, OSError) as exc:
                log.error("Failed to read config (%s); using defaults", exc)
        cfg = cls(_deep_merge(DEFAULTS, data))
        if not CONFIG_PATH.exists():
            cfg.save()
        return cfg

    def save(self) -> None:
        with self._lock:
            CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
            CONFIG_PATH.write_text(
                json.dumps(self._data, indent=2, ensure_ascii=False),
                encoding="utf-8",
            )
        log.debug("Config saved to %s", CONFIG_PATH)

    # ---------------------------------------------------------------- access
    def get(self, path: str, default: Any = None) -> Any:
        """``config.get("ai.ollama.base_url")``"""
        with self._lock:
            node: Any = self._data
            for part in path.split("."):
                if not isinstance(node, dict) or part not in node:
                    return default
                node = node[part]
            return copy.deepcopy(node)

    def set(self, path: str, value: Any, persist: bool = True) -> None:
        with self._lock:
            parts = path.split(".")
            node = self._data
            for part in parts[:-1]:
                node = node.setdefault(part, {})
            node[parts[-1]] = value
        if persist:
            self.save()

    def as_dict(self) -> dict[str, Any]:
        with self._lock:
            return copy.deepcopy(self._data)
