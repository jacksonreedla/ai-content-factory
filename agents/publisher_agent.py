"""Publisher Agent: direct-posts rendered videos to TikTok with SEO metadata.

TikTok is the sole publisher. The video's SEO title, description and hashtags
are combined into a single TikTok caption (max 2200 UTF-16 runes). Because the
content is AI-generated, posts are labelled as AI-generated by default, which
is both good practice and required by TikTok's guidelines.
"""
from __future__ import annotations

import json
from pathlib import Path

from agents.base import Agent, AgentContext, AgentResult
from api.tiktok_client import TikTokClient, TikTokError
from app.notifications import notify
from database.repositories import (SettingsRepo, StoryRepo, UploadRepo,
                                   VideoRepo)
from models.story import StoryStatus

CAPTION_LIMIT = 2200


def _make_client(ctx: AgentContext) -> TikTokClient:
    """Factory - patchable in tests."""
    return TikTokClient(config=ctx.config)


class PublisherAgent(Agent):
    name = "publisher"
    stage = "upload"

    def _metadata_for(self, ctx: AgentContext, video: dict) -> dict:
        settings = SettingsRepo(ctx.db)
        raw = (settings.get(f"metadata.story.{video['story_id']}")
               if video.get("story_id") else None)
        if raw:
            try:
                return json.loads(raw)
            except json.JSONDecodeError:
                self.log.warning("Bad metadata JSON for story %s",
                                 video["story_id"])
        return {"title": video.get("title") or "Untitled story",
                "description": "", "tags": [], "hashtags": []}

    @staticmethod
    def _build_caption(metadata: dict, video: dict) -> str:
        """Title + description + hashtags, trimmed to TikTok's caption limit."""
        title = (metadata.get("title") or video.get("title")
                 or "Untitled").strip()
        description = (metadata.get("description") or "").strip()
        hashtags = [h if h.startswith("#") else f"#{h}"
                    for h in metadata.get("hashtags", []) if h]

        parts = [title]
        if description and description.lower() != title.lower():
            parts.append(description)
        caption = "\n\n".join(parts)
        if hashtags:
            tag_line = " ".join(hashtags)
            # Only append hashtags that still fit under the limit.
            if len(caption) + len(tag_line) + 2 <= CAPTION_LIMIT:
                caption = (caption + "\n\n" + tag_line).strip()
        return caption[:CAPTION_LIMIT]

    def execute(self, ctx: AgentContext) -> AgentResult:
        video_repo = VideoRepo(ctx.db)
        upload_repo = UploadRepo(ctx.db)
        story_repo = StoryRepo(ctx.db)

        candidates = [v for v in video_repo.recent(200)
                      if v["file_path"] and not upload_repo.is_uploaded(v["id"])]
        if not candidates:
            return AgentResult(ok=True, skipped=True,
                               message="no rendered videos awaiting upload")

        client = _make_client(ctx)
        if not client.is_configured():
            # Not an error: the user simply hasn't set TikTok up yet, so the
            # full pipeline still completes and videos wait in data/output.
            return AgentResult(ok=True, skipped=True, message=(
                f"{len(candidates)} videos ready but TikTok is not "
                f"configured - see the Uploads page to connect."))
        if not client.is_authorized():
            return AgentResult(ok=False, message=(
                "TikTok is configured but not connected. Click 'Connect "
                "TikTok' on the Uploads page to authorize."))

        visibility = ctx.config.get("upload.default_visibility", "public")
        is_aigc = bool(ctx.config.get("tiktok.label_ai_generated", True))
        disable_comment = bool(ctx.config.get("tiktok.disable_comment", False))
        disable_duet = bool(ctx.config.get("tiktok.disable_duet", False))
        disable_stitch = bool(ctx.config.get("tiktok.disable_stitch", False))
        cover_ms = int(ctx.config.get("tiktok.cover_timestamp_ms", 1000))

        # Resolve the privacy level once (a creator_info call) so an unaudited
        # app or a restricted account degrades gracefully to SELF_ONLY.
        try:
            privacy_level = client.resolve_privacy(visibility)
        except TikTokError as exc:
            return AgentResult(ok=False, message=(
                f"Could not read TikTok account info: {exc}"))

        done, failed = 0, 0
        first_error = ""
        for i, video in enumerate(candidates):
            ctx.report(self.stage, i / len(candidates))
            file_path = Path(video["file_path"])
            if not file_path.exists():
                self.log.warning("File missing for video %s: %s",
                                 video["id"], file_path)
                failed += 1
                continue

            metadata = self._metadata_for(ctx, video)
            caption = self._build_caption(metadata, video)

            upload_id = upload_repo.failed_for_video(video["id"])
            if upload_id is None:
                upload_id = upload_repo.add(video["id"], "tiktok", privacy_level)

            try:
                publish_id = client.upload_video(
                    file_path,
                    title=caption,
                    privacy_level=privacy_level,
                    disable_comment=disable_comment,
                    disable_duet=disable_duet,
                    disable_stitch=disable_stitch,
                    is_aigc=is_aigc,
                    cover_timestamp_ms=cover_ms,
                )
                upload_repo.mark_uploaded(upload_id, publish_id)
                if video.get("story_id"):
                    story_repo.set_status(video["story_id"],
                                          StoryStatus.PUBLISHED)
                self.db_set_video_published(ctx, video["id"])
                done += 1
                notify(ctx.config, "TikTok post published",
                       f"{metadata.get('title', file_path.name)} "
                       f"(publish_id {publish_id})")
            except TikTokError as exc:
                self.log.warning("TikTok upload failed for video %s: %s",
                                 video["id"], exc)
                upload_repo.mark_failed(upload_id, str(exc))
                first_error = first_error or str(exc)
                failed += 1

        message = f"{done} posted, {failed} failed"
        if first_error:
            message += f" - first error: {first_error[:200]}"
        if failed and not done:
            notify(ctx.config, "TikTok uploads failed", message,
                   level="warning")
        return AgentResult(ok=done > 0 or failed == 0, message=message,
                           data={"done": done, "failed": failed})

    @staticmethod
    def db_set_video_published(ctx: AgentContext, video_id: int) -> None:
        ctx.db.execute("UPDATE videos SET status = 'published' WHERE id = ?",
                       (video_id,))
